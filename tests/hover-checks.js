/* Hover entries, nested targets, minimized hints, typing/chat/drag guards and no model traffic. */
async page => {
  const base = new URL('.', page.url()).href;
  const checks = [];
  const assert = (value, label) => { if (!value) throw new Error(`FAIL: ${label}`); checks.push(label); };
  let requests = 0, release;
  await page.route('**/api/chat', async route => {
    requests++;
    await new Promise(resolve => { release = resolve; });
    await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({reply:'测试回复，不覆盖指引。'}) });
  });
  const ready = async () => page.waitForFunction(() => Boolean(window.Zimo?.chat) && !window.Zimo.effects.transitioning);
  const away = () => page.mouse.move(1300, 100);
  const watch = () => page.evaluate(() => {
    window.__remarkCount = 0;
    const comment = window.Zimo.mascot.comment;
    window.Zimo.mascot.comment = (...args) => { const result = comment(...args); if (result) window.__remarkCount++; return result; };
  });
  const count = () => page.evaluate(() => window.__remarkCount);
  try {
    await page.setViewportSize({width:1440,height:1000});
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.goto(base+'?lang=zh'); await ready();
    await page.evaluate(() => { localStorage.setItem('zimo.mascot','open');localStorage.setItem('zimo.music','off');sessionStorage.setItem('zimo.susu.greeted','true');localStorage.removeItem('zimo.mascotPosition.desktop'); });
    await page.reload(); await ready(); await away(); await watch();
    await page.locator('#susu-stage').hover();
    await page.waitForFunction(()=>window.__remarkCount===1);
    assert(await page.locator('#susu-bubble').isVisible(), 'a single mouse entry immediately reveals a remark');
    assert(await page.locator('#susu-bubble').evaluate(n=>n.classList.contains('is-commenting')), 'local remarks have a distinct readable bubble');
    assert(await page.locator('#susu-message').evaluate(n=>parseFloat(getComputedStyle(n).fontSize)>=13), 'remark text is larger than the old tiny guide copy');
    const first = await page.locator('#susu-message').textContent();
    const stage = await page.locator('#susu-stage').boundingBox();
    await page.mouse.move(stage.x+15,stage.y+15);
    await page.mouse.move(stage.x+stage.width-15,stage.y+stage.height-15);
    await page.waitForTimeout(250);
    assert(await count()===1, 'moving within the same character does not spam new lines');
    await away(); await page.locator('#susu-stage').hover();
    await page.waitForFunction(()=>window.__remarkCount===2);
    assert(await page.locator('#susu-message').textContent()!==first, 'leaving and entering again changes the line without a twenty-second wait');
    await page.locator('[data-nav-section="winter"]').hover();
    await page.waitForFunction(()=>window.__remarkCount===3);
    const winterText = await page.locator('#susu-message').textContent();
    assert(/寒假|勾选|程序|模型|前端|参考文档|玩/.test(winterText), 'hovering a navigation item chooses relevant remarks first');
    await page.locator('[data-nav-section="winter"] svg').hover();
    await page.waitForTimeout(250);
    assert(await count()===3 && await page.locator('#susu-message').textContent()===winterText, 'crossing a link icon does not count as a fresh entry');
    await page.locator('#susu-stage').click();
    assert(await page.locator('#susu-choices').isVisible(), 'click still opens the complete navigation guide');
    await page.locator('#susu-chat-toggle').click();
    const chatText = await page.locator('#susu-message').textContent();
    const beforeChat = await count();
    await away(); await page.locator('#susu-stage').hover(); await page.waitForTimeout(250);
    assert(await count()===beforeChat && await page.locator('#susu-message').textContent()===chatText, 'hover cannot replace an active conversation');
    await page.locator('#susu-chat-input').fill('hover test');
    await page.locator('#susu-chat-send').click();
    await page.waitForFunction(()=>window.Zimo.chat.busy);
    await page.locator('#susu-guide-mode').click();
    const guideText = await page.locator('#susu-message').textContent();
    await away(); await page.locator('#susu-stage').hover(); await page.waitForTimeout(250);
    assert(await page.locator('#susu-message').textContent()===guideText, 'hover also respects a reply pending behind guide mode');
    release(); await page.waitForFunction(()=>!window.Zimo.chat.busy);
    assert(requests===1, 'only the explicit test chat sent a model request');
    await page.goto(new URL('archive.html?lang=zh',base).href);await ready();await watch();
    await page.locator('#archive-query').fill('Flutter');
    await page.locator('#susu-stage').hover();await page.waitForTimeout(250);
    assert(await count()===0, 'hover stays quiet while typing in the archive search field');
    await page.locator('#archive-query').evaluate(n=>n.blur());
    await away();await page.locator('#susu-stage').hover();
    await page.waitForFunction(()=>window.__remarkCount===1);
    const moved=await page.locator('#susu-stage').boundingBox();
    await page.mouse.move(moved.x+moved.width/2,moved.y+moved.height/2);await page.mouse.down();
    await page.mouse.move(moved.x-130,moved.y-90,{steps:8});await page.waitForTimeout(250);
    assert(await page.evaluate(()=>window.Zimo.mascot.dragging) && await page.locator('#susu-bubble').isHidden(), 'dragging does not create distracting hover remarks');
    await page.mouse.up();
    assert((await page.locator('#susu-message').textContent()).includes('搬家'), 'drop feedback remains intact');
    await page.locator('[data-language="en"]').click();await away();
    await page.locator('#susu-stage').hover();
    await page.waitForFunction(()=>document.getElementById('susu-bubble').classList.contains('is-commenting')&&!/[\u4e00-\u9fff]/.test(document.getElementById('susu-message').textContent));
    assert(!/[\u4e00-\u9fff]/.test(await page.locator('#susu-message').textContent()), 'hover remarks follow the selected language');
    await page.locator('#susu-minimize').click();await away();
    await page.locator('#susu-launch').hover();
    await page.locator('#susu-peek').waitFor({state:'visible'});
    assert(await page.locator('#susu-mascot').isHidden(), 'minimized Susu can speak without expanding herself');
    assert(await page.evaluate(()=>localStorage.getItem('zimo.mascot')==='closed'), 'a minimized hover does not overwrite the visitor’s preference');
    const peek=await page.locator('#susu-peek').textContent();
    await away();await page.locator('#susu-launch').hover();
    await page.waitForFunction(old=>document.getElementById('susu-peek').textContent!==old,peek);
    assert(await page.locator('#susu-peek').textContent()!==peek, 'each launcher entry gets a fresh remark too');
    await page.locator('#susu-launch').click();
    assert(await page.locator('#susu-peek').isHidden() && await page.locator('#susu-choices').isVisible(), 'clicking the launcher replaces the small hint with the normal guide');
    await page.locator('#susu-minimize').click();
    await page.setViewportSize({width:390,height:844});
    await page.locator('#susu-launch').dispatchEvent('pointerover',{pointerType:'touch',isPrimary:true});await page.waitForTimeout(250);
    assert(await page.locator('#susu-peek').isHidden(), 'touch-generated pointer events do not accidentally fire desktop hover hints');
    assert(requests===1, 'all hover and focus remarks remain local-only');
    return {passed:checks.length,checks};
  } finally {release?.();await page.unroute('**/api/chat');}
}
