/* Real dragging, privacy boundaries, looping, and continuous same-document playback. */
async page => {
  const base = new URL(".", page.url()).href;
  const checks = [];
  const errors = [];
  const onError = error => errors.push(error.message);
  page.on("pageerror", onError);
  const assert = (condition, label) => { if (!condition) throw new Error(`FAIL: ${label}`); checks.push(label); };
  const settled = async () => {
    await page.waitForFunction(() => Boolean(window.Zimo?.navigation));
    await page.waitForFunction(() => !window.Zimo.navigation.busy && !window.Zimo.effects.transitioning && getComputedStyle(document.querySelector(".scene-overlay")).visibility === "hidden");
  };
  try {
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.emulateMedia({ reducedMotion: "no-preference", colorScheme: "light" });
    await page.goto(base + "?lang=zh");
    await settled();
    await page.evaluate(() => {
      localStorage.setItem("zimo.mascot", "open");
      localStorage.removeItem("zimo.mascotPosition.desktop");
      localStorage.removeItem("zimo.mascotPosition.mobile");
      localStorage.setItem("zimo.music", "off");
      sessionStorage.setItem("zimo.susu.greeted", "true");
    });
    await page.reload(); await settled();
    await page.waitForFunction(() => !document.getElementById("susu-stage").classList.contains("is-loading"));
    assert(await page.evaluate(() => window.Zimo.navigation.canVisit(new URL("archive", document.baseURI))), "navigation accepts static-host canonical URLs without .html");
    assert(await page.locator(".research-workspace-card").count() === 3, "research interests are represented without detailed unpublished case studies");
    assert(await page.locator("#research-workspace a").count() === 0, "unpublished research has no public detail or repository links");
    assert(await page.evaluate(() => window.PORTFOLIO.researchInterests.every(item => item.overviewOnly && !item.overview && !item.highlights && !item.boundary && item.links.length === 0)), "no hidden unpublished research methods are embedded in JavaScript");
    assert(await page.locator(".poetry-card").count() === 5, "five attributed poetry interludes are present");
    assert(await page.locator(".poetry-verse:not([lang=en])").count() === 0, "poetry stays in English on the Chinese homepage");
    assert(await page.locator(".poetry-reflection").count() === 0, "poems have no Chinese translation or explanatory captions");
    assert((await page.locator(".intro-signature").textContent()).includes("stay young, stay simple, stay hungry, stay foolish"), "personal signature uses the requested wording");
    assert(await page.locator(".email-row a").getAttribute("href") === "mailto:zimozeng961@gmail.com", "Gmail is the primary public email");
    assert((await page.locator(".secondary-email").textContent()).includes("2319597720@qq.com"), "QQ remains an alternative contact");
    const before = await page.locator("#susu-mascot").boundingBox();
    const stage = await page.locator("#susu-stage").boundingBox();
    await page.mouse.move(stage.x + 72, stage.y + 65);
    await page.mouse.down();
    await page.mouse.move(960, 450, { steps: 20 });
    await page.mouse.up();
    const moved = await page.locator("#susu-mascot").boundingBox();
    assert(Math.abs(moved.x - before.x) > 100 && Math.abs(moved.y - before.y) > 100, "Susu follows real pointer dragging");
    assert((await page.locator("#susu-message").textContent()).includes("搬家成功"), "drag release responds without firing the click greeting");
    const stored = await page.evaluate(() => JSON.parse(localStorage.getItem("zimo.mascotPosition.desktop")));
    assert(Number.isFinite(stored.x) && Number.isFinite(stored.y), "drag position is stored as viewport-relative coordinates");
    await page.reload(); await settled();
    const restored = await page.locator("#susu-mascot").boundingBox();
    assert(Math.abs(restored.x - moved.x) < 3 && Math.abs(restored.y - moved.y) < 3, "Susu remembers her position after reload");
    await page.locator("#susu-stage").focus();
    await page.keyboard.press("ArrowLeft");
    const keyboard = await page.locator("#susu-mascot").boundingBox();
    assert(keyboard.x < restored.x - 10, "keyboard users can reposition Susu with arrow keys");
    const start = await page.locator("#susu-stage").boundingBox();
    await page.mouse.move(start.x + 72, start.y + 55);
    await page.mouse.down(); await page.mouse.move(2, 2, { steps: 20 }); await page.mouse.up();
    const clamped = await page.locator("#susu-mascot").boundingBox();
    const bubble = await page.locator("#susu-bubble").boundingBox();
    assert(clamped.x >= 9 && clamped.y >= 75, "dragging keeps Susu inside the viewport and away from the header");
    assert(bubble.x >= 0 && bubble.y >= 0 && bubble.x + bubble.width <= 1441, "speech stays on screen after dragging to an edge");
    await page.locator("#susu-reset").click();
    const reset = await page.locator("#susu-mascot").boundingBox();
    assert(reset.x > 1200 && reset.y > 700, "one-click reset returns Susu to her corner");
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator("#susu-stage").focus(); await page.keyboard.press("ArrowLeft");
    assert(await page.evaluate(() => Boolean(localStorage.getItem("zimo.mascotPosition.mobile"))), "mobile and desktop positions are saved separately");
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator("#susu-reset").click();
    if (await page.locator("#susu-bubble").isVisible()) await page.locator("#susu-dismiss").click();
    await page.locator("#music-toggle").click();
    await page.waitForFunction(() => window.Zimo.music.audio.readyState >= 3 && window.Zimo.music.playing);
    await page.evaluate(() => { window.__originalAudio = window.Zimo.music.audio; window.__pageMarker = "continuous-playback"; window.Zimo.music.audio.currentTime = window.Zimo.music.audio.duration - .4; });
    await page.waitForFunction(() => window.Zimo.music.audio.currentTime < 3 && window.Zimo.music.playing);
    assert(await page.evaluate(() => window.Zimo.music.playing && !window.Zimo.music.audio.ended), "actual playback wraps from the end into the next loop");
    await page.locator(".project-body h3 a").first().click(); await settled();
    assert(await page.evaluate(() => window.__originalAudio === window.Zimo.music.audio && window.__pageMarker === "continuous-playback"), "project navigation preserves the actual audio element and document");
    assert(await page.evaluate(() => window.Zimo.music.playing), "piano keeps playing during project navigation");
    assert(await page.evaluate(() => window.Zimo.page === "project"), "the project view mounts after navigation");
    assert(await page.locator("#music-player").count() === 1 && await page.locator("#susu-mascot").count() === 1, "navigation does not duplicate the player or companion");
    await page.goBack(); await settled();
    assert(await page.evaluate(() => window.Zimo.page === "home" && window.__originalAudio === window.Zimo.music.audio), "browser Back restores the home view without restarting music");
    await page.goForward(); await settled();
    assert(await page.evaluate(() => window.Zimo.page === "project" && window.Zimo.music.playing), "browser Forward also preserves playback");
    await page.locator('#header-navigation [data-nav-section="archive"]').click(); await settled();
    assert(await page.locator(".archive-entry").count() === 10, "archive counts only public projects and notes");
    await page.locator("#archive-query").fill("Flutter");
    await page.locator(".archive-entry").first().click(); await settled();
    assert((await page.locator("h1").textContent()).includes("记账"), "search-result navigation opens the matching public project");
    await page.goBack(); await settled();
    assert(await page.locator("#archive-query").inputValue() === "Flutter", "Back preserves the archive query in the URL");
    await page.locator('[data-language="en"]').click();
    assert(await page.locator("html").getAttribute("lang") === "en", "language switching works after several soft navigations");
    await page.locator(".brand").first().click(); await settled();
    assert(await page.locator(".poetry-verse").count() === 5 && await page.locator("#main-content").count() === 1, "home remount has poetry but no duplicate page containers");
    await page.locator("#music-toggle").click();
    assert(await page.evaluate(() => !window.Zimo.music.playing), "continuous player can still be paused");
    assert(errors.length === 0, `no uncaught errors (${errors.join("; ")})`);
    return { passed: checks.length, checks, browserErrors: errors };
  } finally { page.off("pageerror", onError); }
}
